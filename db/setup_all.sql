-- =====================================================================
-- Kenali Batikmu — skema Supabase (PostgreSQL)
-- Jalankan di Supabase Dashboard -> SQL Editor. Aman dijalankan ulang.
--
-- Nama tabel & kolom sengaja sama dengan yang sudah dipakai aplikasi mobile
-- (users, batik_motifs, modules, user_module_progress, quiz_attempts, scans).
-- Yang BARU: refresh_tokens, password_resets, kolom synced_at & client_ref.
--
-- Isi modul, soal kuis, dan model pemindai TIDAK disimpan di sini: semuanya
-- ada di aplikasi (offline). Tabel modules/batik_motifs hanya data referensi
-- (id, judul, KKM) agar progres bisa divalidasi.
-- =====================================================================

-- ---------------------------------------------------------------- users
create table if not exists public.users (
  id                 bigint generated by default as identity primary key,
  name               text        not null,
  email              text        not null,
  phone              text,
  password_hash      text        not null,
  failed_attempts    integer     not null default 0,
  lockout_until      timestamptz,
  profile_image_path text,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
alter table public.users add column if not exists failed_attempts integer not null default 0;
alter table public.users add column if not exists lockout_until   timestamptz;
create unique index if not exists users_email_lower_key on public.users (lower(email));

-- ---------------------------------------------------------------- referensi
create table if not exists public.batik_motifs (
  id                bigint  primary key,
  name              text    not null,
  slug              text    not null unique,
  origin_region     text    not null default '',
  short_description text    not null default '',
  thumbnail_url     text,
  ml_class_index    integer not null unique check (ml_class_index >= 0)
);

create table if not exists public.modules (
  id            bigint  primary key,
  motif_id      bigint  not null references public.batik_motifs (id),
  title         text    not null,
  description   text    not null default '',
  cover_image   text,
  video_url     text,
  passing_score integer not null default 70 check (passing_score between 0 and 100),
  order_no      integer not null unique
);

-- ---------------------------------------------------------------- progres per pengguna
create table if not exists public.user_module_progress (
  id               bigint generated by default as identity primary key,
  user_id          bigint  not null references public.users (id)   on delete cascade,
  module_id        bigint  not null references public.modules (id) on delete cascade,
  status           text    not null default 'not_started'
                   check (status in ('not_started', 'in_progress', 'completed')),
  progress_percent integer not null default 0 check (progress_percent between 0 and 100),
  history_done     boolean not null default false,
  character_done   boolean not null default false,
  gallery_done     boolean not null default false,
  quiz_done        boolean not null default false,
  practice_done    boolean not null default false,
  quiz_score       integer check (quiz_score     between 0 and 100),
  practice_score   integer check (practice_score between 0 and 100),
  passing_score    integer not null default 70,
  is_passed        boolean not null default false,
  completed_at     timestamptz,
  last_accessed_at timestamptz not null default now(),
  synced_at        timestamptz not null default now(),
  constraint user_module_progress_user_module_key unique (user_id, module_id)
);
alter table public.user_module_progress add column if not exists synced_at timestamptz not null default now();
create index if not exists user_module_progress_sync_idx on public.user_module_progress (user_id, synced_at);

-- ---------------------------------------------------------------- riwayat kuis teori
create table if not exists public.quiz_attempts (
  id              bigint generated by default as identity primary key,
  user_id         bigint  not null references public.users (id)   on delete cascade,
  module_id       bigint  not null references public.modules (id) on delete cascade,
  score           integer not null check (score between 0 and 100),
  passed          boolean not null,
  total_questions integer,
  attempted_at    timestamptz not null default now(),
  client_ref      text,
  synced_at       timestamptz not null default now()
);
alter table public.quiz_attempts add column if not exists total_questions integer;
alter table public.quiz_attempts add column if not exists client_ref      text;
alter table public.quiz_attempts add column if not exists synced_at       timestamptz not null default now();
create index if not exists quiz_attempts_user_module_idx on public.quiz_attempts (user_id, module_id, attempted_at desc);
create index if not exists quiz_attempts_sync_idx        on public.quiz_attempts (user_id, synced_at);

-- client_ref unik per pengguna => kirim ulang dari perangkat tidak menggandakan data.
-- (NULL dianggap berbeda, jadi percobaan tanpa client_ref tetap boleh banyak.)
do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'quiz_attempts_user_client_ref_key') then
    alter table public.quiz_attempts
      add constraint quiz_attempts_user_client_ref_key unique (user_id, client_ref);
  end if;
end $$;

-- ---------------------------------------------------------------- hasil praktikum (scan_type = 'kuismu')
create table if not exists public.scans (
  id                bigint generated by default as identity primary key,
  user_id           bigint not null references public.users (id) on delete cascade,
  scan_type         text   not null check (scan_type in ('universal', 'kuismu')),
  module_id         bigint references public.modules (id),
  image_path        text,
  top_motif_id      bigint references public.batik_motifs (id),
  confidence        real check (confidence between 0 and 1),
  fit_score         real check (fit_score  between 0 and 1),
  passed            boolean,
  inference_time_ms integer,
  created_at        timestamptz not null default now(),
  synced_at         timestamptz not null default now(),
  check (scan_type = 'universal' or module_id is not null)
);
alter table public.scans add column if not exists synced_at timestamptz not null default now();
-- 1 hasil praktikum per pengguna per modul (sama seperti aturan di aplikasi)
create unique index if not exists scans_user_module_kuismu_key
  on public.scans (user_id, module_id) where scan_type = 'kuismu';
create index if not exists scans_sync_idx on public.scans (user_id, synced_at);

-- ---------------------------------------------------------------- sesi & pemulihan sandi
create table if not exists public.refresh_tokens (
  id           bigint generated by default as identity primary key,
  user_id      bigint      not null references public.users (id) on delete cascade,
  token_hash   text        not null unique,
  expires_at   timestamptz not null,
  revoked_at   timestamptz,
  last_used_at timestamptz,
  created_at   timestamptz not null default now()
);
create index if not exists refresh_tokens_user_idx on public.refresh_tokens (user_id);

create table if not exists public.password_resets (
  id               bigint generated by default as identity primary key,
  user_id          bigint      not null references public.users (id) on delete cascade,
  otp_hash         text        not null,
  attempts         integer     not null default 0,
  verified         boolean     not null default false,
  reset_token_hash text,
  expires_at       timestamptz not null,
  used_at          timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists password_resets_user_idx on public.password_resets (user_id, created_at desc);
create index if not exists password_resets_token_idx on public.password_resets (reset_token_hash);

-- ---------------------------------------------------------------- keamanan (RLS)
-- Backend memakai service_role key (melewati RLS). Kunci "anon" yang ada di aplikasi
-- TIDAK boleh bisa membaca/menulis data pengguna, termasuk password_hash.
alter table public.users                enable row level security;
alter table public.user_module_progress enable row level security;
alter table public.quiz_attempts        enable row level security;
alter table public.scans                enable row level security;
alter table public.refresh_tokens       enable row level security;
alter table public.password_resets      enable row level security;
alter table public.batik_motifs         enable row level security;
alter table public.modules              enable row level security;

revoke all on public.users, public.user_module_progress, public.quiz_attempts,
              public.scans, public.refresh_tokens, public.password_resets
  from anon, authenticated;

-- Data referensi (non-sensitif) boleh dibaca publik, sehingga sinkron master data
-- di aplikasi yang sekarang membaca langsung dari Supabase tetap berjalan.
drop policy if exists "reference_read" on public.batik_motifs;
create policy "reference_read" on public.batik_motifs for select to anon, authenticated using (true);
drop policy if exists "reference_read" on public.modules;
create policy "reference_read" on public.modules      for select to anon, authenticated using (true);

-- ---------------------------------------------------------------- storage
-- Bucket publik untuk foto profil & foto praktikum (diunggah lewat backend).
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values
  ('avatars',   'avatars',   true, 5242880, array['image/jpeg', 'image/png']),
  ('practices', 'practices', true, 5242880, array['image/jpeg', 'image/png'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

